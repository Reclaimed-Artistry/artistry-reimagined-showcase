export const BOOK_BY_NUMBER = new Map<number, CanonicalBookMeta>(
  CANONICAL_BOOKS.map((b) => [b.bookNumber, b])
);

export const BOOK_BY_USFM = new Map<string, CanonicalBookMeta>(
  CANONICAL_BOOKS.map((b) => [b.usfm.toUpperCase(), b])
);

export const BOOK_BY_CDN_ABBREV = new Map<string, CanonicalBookMeta>(
  CANONICAL_BOOKS.map((b) => [b.cdnAbbrev.toLowerCase(), b])
);

export function getBookMeta(bookNumber: number): CanonicalBookMeta {
  return BOOK_BY_NUMBER.get(bookNumber) || CANONICAL_BOOKS[0];
}

export interface ParsedScriptureRef {
  bookNumber: number;
  bookName: string;
  chapter: number;
  verse?: number;
  verseEnd?: number;
}

/**
 * Parses human references like "John 3:16", "1 Cor 13:4-7", "Ps 23", "Gen 1", "Rom 8:28"
 */
export function parseScriptureReference(input: string): ParsedScriptureRef | null {
  const cleaned = input.trim().replace(/\s+/g, " ");
  if (!cleaned) return null;

  const match = cleaned.match(
    /^([1-3]?\s*[a-zA-ZÀ-ÿ.\s]+?)(?:\s+(\d+)(?::(\d+)(?:\s*[-–]\s*(\d+))?)?)?$/
  );
  if (!match) return null;

  const rawBook = match[1].toLowerCase().replace(/\./g, "").trim();
  const rawChapter = match[2] ? parseInt(match[2], 10) : 1;
  const rawVerse = match[3] ? parseInt(match[3], 10) : undefined;
  const rawVerseEnd = match[4] ? parseInt(match[4], 10) : undefined;

  let foundBook = CANONICAL_BOOKS.find(
    (b) =>
      b.name.toLowerCase() === rawBook ||
      b.shortName.toLowerCase() === rawBook ||
      b.usfm.toLowerCase() === rawBook ||
      b.aliases.includes(rawBook)
  );

  if (!foundBook && rawBook.length >= 3) {
    foundBook = CANONICAL_BOOKS.find(
      (b) =>
        b.name.toLowerCase().startsWith(rawBook) ||
        b.aliases.some((a) => a.startsWith(rawBook))
    );
  }

  if (!foundBook) return null;

  const safeChapter = Math.max(1, Math.min(foundBook.chapters, rawChapter || 1));

  return {
    bookNumber: foundBook.bookNumber,
    bookName: foundBook.name,
    chapter: safeChapter,
    verse: rawVerse,
    verseEnd: rawVerseEnd,
  };
}

export function formatReference(
  bookNumber: number,
  chapter: number,
  verse?: number,
  verseEnd?: number
): string {
  const book = getBookMeta(bookNumber);
  if (!verse) return `${book.name} ${chapter}`;
  if (verseEnd && verseEnd > verse) return `${book.name} ${chapter}:${verse}-${verseEnd}`;
  return `${book.name} ${chapter}:${verse}`;
}
